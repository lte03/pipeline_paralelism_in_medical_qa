def pubmedqa_json_to_dataset(json_path):
    with open(json_path, "r", encoding="utf-8") as f:
        raw = json.load(f)

    rows = []
    for pmid, ex in raw.items():
        rows.append({
            "pmid": str(pmid),
            "question": ex.get("QUESTION", ""),
            "context": "\n".join(ex.get("CONTEXTS", [])),
            "section_labels": ex.get("LABELS", []),
            "meshes": ex.get("MESHES", []),
            "year": int(ex["YEAR"]) if str(ex.get("YEAR","")).isdigit() else 0,
            "final_decision": ex.get("final_decision", ""),  # STRING
            "long_answer": ex.get("LONG_ANSWER", "")
        })

    features = Features({
        "pmid": Value("string"),
        "question": Value("string"),
        "context": Value("string"),
        "section_labels": Sequence(Value("string")),
        "meshes": Sequence(Value("string")),
        "year": Value("int32"),
        "final_decision": Value("string"),
        "long_answer": Value("string"),
    })

    return Dataset.from_list(rows, features=features)

def tokenize_function(examples, max_length=512):
    input_ids_list = []
    attention_mask_list = []
    labels_list = []

    answer_map = {
        "yes": "A",
        "no": "B",
        "maybe": "C"
    }

    for context, question, decision in zip(
        examples["context"],
        examples["question"],
        examples["final_decision"]
    ):
        if isinstance(decision, list):
            decision = decision[0]

        decision = decision.lower().strip()
        if decision not in answer_map:
            continue

        # Qwen chat template formatı
        messages = [
            {
                "role": "system",
                "content": "You are a medical expert. Based on the context provided, answer the question by selecting one option. Provide your final answer as one of the options A, B, or C. Your final response should only be the letter corresponding to your chosen option."
            },
            {
                "role": "user",
                "content": f"Context: {context}\n\nQuestion: {question}\n\nOptions:\nA: yes\nB: no\nC: maybe"
            }
        ]

        # Chat template uygula
        prompt = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True
        )

        target = answer_map[decision]

        # Tokenize
        prompt_ids = tokenizer.encode(prompt, add_special_tokens=False)
        target_ids = tokenizer.encode(target, add_special_tokens=False)

        input_ids = prompt_ids + target_ids
        labels = [-100] * len(prompt_ids) + target_ids

        # Truncate
        input_ids = input_ids[:max_length]
        labels = labels[:max_length]

        attention_mask = [1] * len(input_ids)

        # Padding
        pad_len = max_length - len(input_ids)
        input_ids += [tokenizer.pad_token_id] * pad_len
        attention_mask += [0] * pad_len
        labels += [-100] * pad_len

        input_ids_list.append(input_ids)
        attention_mask_list.append(attention_mask)
        labels_list.append(labels)

    return {
        "input_ids": input_ids_list,
        "attention_mask": attention_mask_list,
        "labels": labels_list
    }

